"""
Builds src/data/media.generated.ts from every image in public/images/.

For each JPG/PNG/WebP it records the intrinsic width/height (so layouts never
jump) and a tiny blurred WebP preview used as a placeholder while the full
photo loads.

Run after adding or replacing photographs:
    pip install pillow
    python3 scripts/build-media-manifest.py
"""
import base64, io, json, os, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..")
PUBLIC = os.path.join(ROOT, "public")
OUT = os.path.join(ROOT, "src", "data", "media.generated.ts")
EXTS = (".jpg", ".jpeg", ".png", ".webp")

entries = {}
for dirpath, _, files in os.walk(os.path.join(PUBLIC, "images")):
    for f in sorted(files):
        if not f.lower().endswith(EXTS):
            continue
        path = os.path.join(dirpath, f)
        src = "/" + os.path.relpath(path, PUBLIC).replace(os.sep, "/")
        with Image.open(path) as im:
            w, h = im.size
            thumb = im.convert("RGB")
            thumb.thumbnail((16, 16))
            buf = io.BytesIO()
            thumb.save(buf, "WEBP", quality=40)
        entries[src] = {
            "width": w,
            "height": h,
            "blurDataURL": "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode(),
        }

with open(OUT, "w") as fh:
    fh.write("// AUTO-GENERATED by scripts/build-media-manifest.py — do not edit by hand.\n")
    fh.write("export type MediaInfo = { width: number; height: number; blurDataURL: string };\n\n")
    fh.write("export const media: Record<string, MediaInfo> = ")
    fh.write(json.dumps(dict(sorted(entries.items())), indent=2))
    fh.write(";\n")

print(f"wrote {len(entries)} entries → {os.path.relpath(OUT, ROOT)}", file=sys.stderr)
